#[test]
fn directory_lists_five_populated_profiles_at_sectors_one_through_five() {
    let entries = parse_profile_directory(&G502_X_LIGHTSPEED_DIRECTORY);
    let addresses: Vec<u16> = entries.iter().map(|e| e.address).collect();
    assert_eq!(addresses, [1, 2, 3, 4, 5]);
}

#[test]
fn real_button_table_decodes_to_the_expected_bindings() {
    let sector = G502_LIGHTSPEED_PROFILE_1;
    let table = &sector[32..];
    let decoded: Vec<ButtonBinding> = table
        .as_chunks::<4>()
        .0
        .iter()
        .map_while(|&entry| match ButtonBinding::parse(entry) {
            Ok(ButtonBinding::Disabled) | Err(_) => None,
            Ok(binding) => Some(binding),
        })
        .collect();

    assert_eq!(
        decoded,
        [
            ButtonBinding::Mouse { buttons: 0x0001 },
            ButtonBinding::Mouse { buttons: 0x0002 },
            ButtonBinding::Mouse { buttons: 0x0004 },
            ButtonBinding::Mouse { buttons: 0x0008 },
            ButtonBinding::Mouse { buttons: 0x0010 },
            ButtonBinding::Special(SpecialFunction::ShiftDpi),
            ButtonBinding::Special(SpecialFunction::PrevDpi),
            ButtonBinding::Special(SpecialFunction::NextDpi),
            ButtonBinding::Special(SpecialFunction::BatteryIndicator),
            ButtonBinding::Special(SpecialFunction::TiltRight),
            ButtonBinding::Special(SpecialFunction::TiltLeft),
        ]
    );
}

#[test]
fn round_tripping_a_real_sector_through_the_crc_reproduces_its_own_trailer() {
    // write_sector() always re-stamps the last 2 bytes with a fresh CRC
    // before sending; assert that doing so to an already-valid real sector
    // is a no-op on those bytes, which is exactly what a round-trip write
    // (read -> write back unmodified -> read again) depends on.
    let mut sector = G502_X_LIGHTSPEED_PROFILE_1;
    let original_trailer = [sector[253], sector[254]];
    let crc = crc_ccitt(&sector[..253]);
    sector[253..].copy_from_slice(&crc.to_be_bytes());
    assert_eq!([sector[253], sector[254]], original_trailer);
}
