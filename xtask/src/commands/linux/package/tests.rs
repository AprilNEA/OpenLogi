use super::{PACKAGE_NAME, PACKAGED_BINS, nfpm_version, pkgver};

/// `nfpm.yaml` decides what actually ships, so a binary listed there but
/// missing from [`PACKAGED_BINS`] is never built — the drift that shipped
/// releases whose overlay came from a stale build cache rather than source.
#[test]
fn packaged_bins_cover_every_binary_nfpm_installs() {
    let config = include_str!("../../../../../packaging/linux/nfpm.yaml");
    let mut installed: Vec<&str> = config
        .lines()
        .filter_map(|line| line.trim().strip_prefix("- src: target/release/"))
        .collect();
    installed.sort_unstable();

    let mut built = PACKAGED_BINS;
    built.sort_unstable();

    assert_eq!(
        installed, built,
        "packaging/linux/nfpm.yaml and PACKAGED_BINS disagree on which binaries ship"
    );
}

/// The Arch check finds the package by the name nfpm gives its file.
#[test]
fn package_name_is_the_one_nfpm_builds() {
    let config = include_str!("../../../../../packaging/linux/nfpm.yaml");
    let name = config
        .lines()
        .find_map(|line| line.strip_prefix("name: "))
        .map(|name| name.trim().trim_matches('"'));

    assert_eq!(name, Some(PACKAGE_NAME));
}

#[test]
fn an_arch_beta_keeps_its_pre_release_in_pkgver() {
    assert_eq!(nfpm_version("archlinux", "0.8.18-beta.1"), "0.8.18beta.1");
    assert_eq!(nfpm_version("archlinux", "0.8.18-beta.10"), "0.8.18beta.10");
    assert_eq!(
        nfpm_version("archlinux", "0.8.18-rc-1.2"),
        "0.8.18rc_1.2",
        "the hyphens nfpm's Arch file name turns into underscores"
    );
}

#[test]
fn final_releases_and_other_packagers_get_the_version_unchanged() {
    assert_eq!(nfpm_version("archlinux", "0.8.18"), "0.8.18");
    assert_eq!(nfpm_version("deb", "0.8.18-beta.1"), "0.8.18-beta.1");
    assert_eq!(nfpm_version("rpm", "0.8.18-beta.1"), "0.8.18-beta.1");
}

#[test]
fn pkgver_is_read_from_its_own_line() {
    let pkginfo = "# Generated by nfpm\npkgname = openlogi\npkgbase = openlogi\npkgver = 0.8.18beta.1-1\npkgdesc = OpenLogi\n";

    assert_eq!(pkgver(pkginfo), Some("0.8.18beta.1-1"));
    assert_eq!(pkgver("pkgname = openlogi\n"), None);
}
